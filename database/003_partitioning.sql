  END IF;
  IF to_regclass('analytics.analytics_events') IS NOT NULL THEN
    ALTER TABLE analytics.analytics_events ALTER COLUMN id SET GENERATED BY DEFAULT;
  END IF;
END $$;

CREATE OR REPLACE FUNCTION app.ensure_event_monthly_partitions(months_back INT DEFAULT 1, months_ahead INT DEFAULT 12)
RETURNS VOID
LANGUAGE plpgsql
AS $$
DECLARE
  i INT;
  m_start DATE;
  m_end DATE;
  part_name TEXT;
BEGIN
  FOR i IN -months_back..months_ahead LOOP
    m_start := (date_trunc('month', NOW())::date + (i || ' month')::interval)::date;
    m_end := (m_start + INTERVAL '1 month')::date;

    part_name := format('audit_events_%s', to_char(m_start, 'YYYYMM'));
    EXECUTE format(
      'CREATE TABLE IF NOT EXISTS audit.%I PARTITION OF audit.audit_events FOR VALUES FROM (%L) TO (%L)',
      part_name, m_start::timestamptz, m_end::timestamptz
    );

    part_name := format('analytics_events_%s', to_char(m_start, 'YYYYMM'));
    EXECUTE format(
      'CREATE TABLE IF NOT EXISTS analytics.%I PARTITION OF analytics.analytics_events FOR VALUES FROM (%L) TO (%L)',
      part_name, m_start::timestamptz, m_end::timestamptz
    );
  END LOOP;
END;
$$;

