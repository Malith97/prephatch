CREATE TABLE IF NOT EXISTS audit.audit_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  organization_id UUID NOT NULL REFERENCES public.organizations(id) ON DELETE RESTRICT,
  actor_user_id UUID REFERENCES public.app_users(id) ON DELETE SET NULL,
  actor_role app_role,
  entity_table TEXT NOT NULL,
  entity_id UUID,
  action TEXT NOT NULL,
  request_id UUID,
  ip INET,
  user_agent TEXT,
  before_data JSONB,
  after_data JSONB,
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb,
  PRIMARY KEY (created_at, id)
) PARTITION BY RANGE (created_at);

CREATE TABLE IF NOT EXISTS analytics.analytics_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY,
  event_time TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  organization_id UUID NOT NULL REFERENCES public.organizations(id) ON DELETE RESTRICT,
  user_id UUID REFERENCES public.app_users(id) ON DELETE SET NULL,
  session_id UUID,
  event_name TEXT NOT NULL,
  properties JSONB NOT NULL DEFAULT '{}'::jsonb,
  PRIMARY KEY (event_time, id)
) PARTITION BY RANGE (event_time);

CREATE TABLE IF NOT EXISTS audit.audit_events_default
  PARTITION OF audit.audit_events DEFAULT;

CREATE TABLE IF NOT EXISTS analytics.analytics_events_default
  PARTITION OF analytics.analytics_events DEFAULT;

DO $$
BEGIN
  IF to_regclass('audit.audit_events') IS NOT NULL THEN
